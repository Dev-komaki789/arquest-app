/**
 * ============================================================
 * instrumentation.ts — サーバーが起動したとき、一度だけ走る処理
 * ============================================================
 *
 * ■ このファイルは何か
 *   Next.js の決まりごとで、src/ の直下に instrumentation.ts を置くと、
 *   export した register() が「サーバーが立ち上がったとき1回だけ」呼ばれる。
 *   本来は監視ツールの組み込みに使う場所だが、
 *   「サーバー全体に効く設定を最初に1回だけしたい」ときにも使える。
 *
 * ■ ここで何を直しているか
 *   Node.js が外部サーバーへ接続するときの「1つのIPアドレスを試す制限時間」を伸ばしている。
 *   既定の250msでは、日本からドイツにある Overpass のサーバーに繋がらないため。
 *
 * ■ なぜそうなるのか（2026-08-01 に自宅PCで実測）
 *   ドメイン名は、複数のIPアドレスを持っていることがある。
 *   overpass-api.de は IPv4が2つ・IPv6が2つの合計4つ。
 *   Node.js は「速いものが勝ち」で全部を少しずつずらして試す方式を取っていて、
 *   1つあたり 250ms 待って繋がらなければ次のアドレスへ移る。
 *
 *   ところが実測した接続時間はこうだった。
 *
 *     65.109.112.52   … 373ms
 *     162.55.144.139  … 315ms
 *
 *   どちらも 250ms を超えている。つまり「あと少しで繋がる」ところで毎回打ち切られ、
 *   4つ全部を試し終えて ETIMEDOUT（時間切れ）になっていた。
 *   ドイツにあるサーバーなので、往復に300ms以上かかるのは異常ではなく普通のこと。
 *
 * ■ 紛らわしかった点
 *   同じPCから curl では成功する。curl はこの方式を使っていないため。
 *   「ネットワークは通っているのにアプリだけ失敗する」という状態になり、
 *   画面には「提供元が混雑している可能性があります」と出る（＝原因を誤解させる）。
 *
 *   また Valhalla（経路）と CARTO（地図タイル）は同じドイツでも成功していた。
 *   こちらはIPアドレスが1組しかなく、次に移る先が無いので打ち切られなかったため。
 *   「一部のAPIだけ落ちる」という、さらに紛らわしい出方をしていた。
 *
 * ■ なぜ 1000ms にしたか
 *   実測の最大が373msなので、余裕を持たせつつ1秒で頭打ちにした。
 *   長くしすぎると、IPv6が本当に繋がらない環境で
 *   IPv4に切り替わるまでの待ち時間がそのまま伸びてしまう。
 *   （このPCのWSLはIPv6が使えず ENETUNREACH になる。その切り替えを遅らせたくない）
 */

export async function register() {
  // Next.js は register() を Edge ランタイムでも呼ぶ。
  // node:net は Node.js ランタイムにしか無いので、そこでだけ読み込む。
  if (process.env.NEXT_RUNTIME !== "nodejs") return;

  const net = await import("node:net");

  net.setDefaultAutoSelectFamilyAttemptTimeout(1000);
}
